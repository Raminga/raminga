// Build the DSH browser bundle from the shared Raminga UI and the DSH adapter.
// The shared UI stays in packages/ui; this script only concatenates its
// dependency-free browser artifact into the supported window.__ModuleLoader__
// lazy factory. No npm runtime dependency is introduced.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const pluginRoot = path.resolve(here, '..');
const repoRoot = path.resolve(pluginRoot, '..', '..');
const sharedRoot = path.join(repoRoot, 'packages', 'ui');
const sharedBundle = path.join(sharedRoot, 'dist', 'raminga-ui.bundle.js');
const template = path.join(pluginRoot, 'ui', 'client.js');
const runtimeTemplate = path.join(pluginRoot, 'ui', 'panel-runtime.js');
const output = path.join(pluginRoot, 'lib', 'ui-client.js');

execFileSync(process.execPath, [path.join(sharedRoot, 'scripts', 'build.mjs'), sharedBundle], { stdio: 'inherit' });
const bundle = fs.readFileSync(sharedBundle, 'utf8');
const source = fs.readFileSync(template, 'utf8');
const marker = '    /*__RAMINGA_UI_BUNDLE__*/';
const runtimeMarker = '    /*__RAMINGA_PANEL_RUNTIME__*/';
if (!source.includes(marker)) throw new Error(`UI client template is missing ${marker}`);
if (!source.includes(runtimeMarker)) throw new Error(`UI client template is missing ${runtimeMarker}`);
const runtime = fs.readFileSync(runtimeTemplate, 'utf8')
  .replace(/^export function /m, 'function ')
  .replace(/\nexport \{ errorText, remoteValue \};\s*$/, '\n');
const body = source.replace(marker, () => bundle.trimEnd()).replace(runtimeMarker, () => runtime.trimEnd());
if (/^\s*import\s/m.test(body)) throw new Error('generated DSH UI client must not contain static imports');
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, `/* Generated by plugins/dsh/scripts/build-ui-client.mjs. Do not edit. */\n${body}`);
console.log(`built ${path.relative(repoRoot, output)} (${fs.statSync(output).size} bytes)`);
